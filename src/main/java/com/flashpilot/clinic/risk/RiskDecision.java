package com.flashpilot.clinic.risk;

/**
 * 风控裁决。
 *
 * <p><b>刻意没有「直接拒绝」这一档。</b>挂号场景里误判一个真实患者的代价极高——
 * 可能是急需就诊的老人，被拒之后不会重试、也不会投诉，只是挂不上号。
 * 而放过一个黄牛的代价是一个号源被倒卖。两者严重程度不对称，
 * 所以处置策略是<b>降权</b>：命中风控的请求仍然能抢，只是被更严的限流挡着，
 * 概率降低但不为零。
 *
 * <p>只有 L3 画像层（有历史失约记录、明确的黑名单）才会真正 BLOCK，
 * 而那个判据来自持久化的行为历史，不是瞬时频次估计。
 */
public enum RiskDecision {

    /** 放行，走正常路径。 */
    PASS,

    /** 降权：走慢车道（更严的限流配额）。仍有机会抢到。 */
    DEMOTE,

    /** 拉黑：只有失约黑名单或人工标记才会到这一档。 */
    BLOCK;

    public boolean allowed() {
        return this != BLOCK;
    }
}
